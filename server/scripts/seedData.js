async function seed() {
  console.log('🌱 Starting KIRSAB database seed...');

  // 1. Seed Categories
  for (const cat of SEED_CATEGORIES) {
    await prisma.category.upsert({
      where: { id: cat.id },
      update: {
        nameHi: cat.nameHi,
        nameEn: cat.nameEn,
        displayOrder: cat.displayOrder,
      },
      create: cat,
    });
  }
  console.log(`✅ Seeded ${SEED_CATEGORIES.length} categories.`);

  // 2. Seed Products
  for (const p of SEED_PRODUCTS) {
    await prisma.product.upsert({
      where: { id: p.id },
      update: {
        nameEn: p.nameEn,
        nameHi: p.nameHi,
        categoryId: p.categoryId,
        unit: p.unit,
        unitHindi: p.unitHindi,
        unitShort: p.unitShort,
        price: p.price,
        isConfigured: p.isConfigured,
        inStock: p.inStock,
        isActive: p.isActive,
        stockQuantity: p.stockQuantity,
        badge: p.badge,
        description: p.description,
        image: p.image,
        fallbackEmoji: p.fallbackEmoji,
      },
      create: p,
    });
  }
  console.log(`✅ Seeded ${SEED_PRODUCTS.length} vegetables with placeholder & unconfigured states.`);

  // 3. Ensure Default Store Settings
  await getOrCreateSettings();
  console.log('✅ Verified default Store Settings.');

  console.log('🎉 Seeding completed successfully!');
}

seed()
  .catch((e) => {
    console.error('❌ Seeding failed:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
